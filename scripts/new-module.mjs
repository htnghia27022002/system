#!/usr/bin/env node
// Scaffolds a CRUD module on both sides of the monorepo:
//
//   BE  be/internal/modules/<name>/  (module, migration, model, dto, repository,
//       service with audit, handler, OpenAPI docs) + registry entry + an
//       integration test
//   FE  fe/src/features/<name>/      (module descriptor, permissions, api + mock,
//       hooks, table, columns, form dialog) + /admin/<name> route + registry
//       entry + EN/VI strings
//
// Usage (repo root):
//   make module name=invoices                          # label "Invoices"
//   node scripts/new-module.mjs projects --label "Client projects" --singular project
//   node scripts/new-module.mjs invoices --dry-run     # list files only
//
// The resource has `name` and `description` fields to start from; extend the
// migration, model, DTOs and form for real fields. Remove a generated module by
// deleting its two folders, its app route, its test, and its registry lines.
import { createHash } from 'node:crypto'
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)))

// ---------- arguments ----------
const args = process.argv.slice(2)
const flags = {}
const positional = []
for (let i = 0; i < args.length; i++) {
  if (args[i] === '--dry-run') flags['--dry-run'] = true
  else if (args[i].startsWith('--')) flags[args[i]] = args[++i]
  else positional.push(args[i])
}
const flag = (key) => flags[key]
const name = positional[0]
const dryRun = Boolean(flags['--dry-run'])

if (!name || !/^[a-z][a-z0-9]{1,30}$/.test(name)) {
  fail('Usage: node scripts/new-module.mjs <name> [--label "Label"] [--singular name] [--dry-run]\n' +
    '<name> is the plural resource in lowercase letters/digits, e.g. invoices.')
}
const reserved = new Set(['auth', 'admin', 'app', 'users', 'roles', 'permissions', 'settings', 'audit', 'dashboard', 'media', 'system', 'webhooks', 'tools', 'account', 'profile'])
if (reserved.has(name)) fail(`"${name}" is used by the core or an existing module; pick another name.`)

const singular = flag('--singular') ?? (name.endsWith('ies') ? name.slice(0, -3) + 'y' : name.endsWith('s') ? name.slice(0, -1) : name)
if (!/^[a-z][a-z0-9]*$/.test(singular) || singular === name) fail(`Pass --singular for "${name}" (got "${singular}").`)
const pascal = (s) => s[0].toUpperCase() + s.slice(1)
const Label = flag('--label') ?? pascal(name)
const N = {
  name, // invoices: resource key, table, route, BE package, FE folder
  singular, // invoice
  Singular: pascal(singular), // Invoice
  Plural: pascal(name), // Invoices
  camel: name, // invoices
  Label, // Invoices
  label: Label.toLowerCase(),
  SingularLabel: flag('--singular-label') ?? pascal(singular),
}
N.singularLabel = N.SingularLabel.toLowerCase()

/** Stable permission UUIDs derived from the module name (never reused). */
function stableUUID(seed) {
  const h = createHash('sha1').update(`module-permission:${seed}`).digest('hex')
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-5${h.slice(13, 16)}-${((parseInt(h[16], 16) & 0x3) | 0x8).toString(16)}${h.slice(17, 20)}-${h.slice(20, 32)}`
}
N.viewID = stableUUID(`${name}:view`)
N.modifyID = stableUUID(`${name}:modify`)

// ---------- helpers ----------
const created = []
function write(rel, content) {
  const file = path.join(root, rel)
  if (existsSync(file)) fail(`${rel} already exists — is "${name}" already generated?`)
  created.push(rel)
  if (dryRun) return
  mkdirSync(path.dirname(file), { recursive: true })
  writeFileSync(file, content.replace(/^\n/, ''))
}
const edits = []
function edit(rel, fn) {
  const file = path.join(root, rel)
  const before = readFileSync(file, 'utf8')
  const after = fn(before)
  if (after === before) fail(`could not update ${rel}`)
  edits.push(rel)
  if (!dryRun) writeFileSync(file, after)
}
function fail(msg) {
  console.error(msg)
  process.exit(1)
}

